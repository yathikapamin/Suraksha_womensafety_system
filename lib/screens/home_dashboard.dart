class HomeDashboard extends StatefulWidget {
  const HomeDashboard({super.key});

  @override
  State<HomeDashboard> createState() => _HomeDashboardState();
}

class _HomeDashboardState extends State<HomeDashboard> {
  int _currentIndex = 0;
  StreamSubscription? _sosSubscription;
  final NearbyAlertService _nearbyService = NearbyAlertService();
  final Set<String> _activeAlertPopups = {}; // Tracks which alerts showed a popup

  final List<Widget> _screens = [
    const _HomeContent(),
    const MapScreen(),
    const AlertScreen(),
    const ProfileScreen(),
  ];

  @override
  void initState() {
    super.initState();
    
    // ── Pre-initialize Discovery ──
    WidgetsBinding.instance.addPostFrameCallback((_) async {
      final loc = Provider.of<LocationProvider>(context, listen: false);
      final auth = Provider.of<AuthProvider>(context, listen: false);
      final notify = NotificationService();
      
      // 1. Initialize GPS & Notifications
      await loc.initialize();
      await notify.initialize();
      
      // 2. Start Low-Power Tracking for Discovery
      // (This ensures responder always has coords for SOS check)
      if (loc.isTracking == false) {
        print('[SOS] Starting Discovery Tracking...');
        loc.startTracking();
      }

      // Start motion detection automatically
      final motion = Provider.of<MotionDetectionService>(context, listen: false);
      motion.onDangerDetected = (event) {
        if (mounted) {
          Navigator.push(
            context,
            MaterialPageRoute(builder: (_) => AutoSOSScreen(motionEvent: event)),
          );
        }
      };
      motion.startMonitoring();

      final audio = Provider.of<AudioDetectionService>(context, listen: false);
      audio.onDangerDetected = (event, db) {
        if (mounted) {
          Navigator.push(
            context,
            MaterialPageRoute(builder: (_) => AutoSOSScreen(audioEvent: event)),
          );
        }
      };

      final voice = Provider.of<VoiceDetectionService>(context, listen: false);
      voice.onDangerDetected = (event, keyword) {
        if (mounted) {
          Navigator.push(
            context,
            MaterialPageRoute(builder: (_) => AutoSOSScreen(voiceEvent: event)),
          );
        }
      };

      // ── Reliable Nearby SOS Listener (Firestore Stream) ──
      _sosSubscription = _nearbyService.getActiveAlertsStream().listen((alerts) {
        if (!mounted) return;
        
        final loc = Provider.of<LocationProvider>(context, listen: false);
        final auth = Provider.of<AuthProvider>(context, listen: false);
        final notify = NotificationService();
        
        if (auth.user == null) return;
        
        if (loc.latitude == null) {
          print('[SOS Listener] Warning: Responder location is NULL. Delaying check...');
          return;
        }

        print('[SOS Listener] Heartbeat: Checking ${alerts.length} active alerts...');

        // Clean up resolved alerts from our popup set
        final currentAliveAlertIds = alerts.map((a) => a.alertId).toSet();
        _activeAlertPopups.removeWhere((id) => !currentAliveAlertIds.contains(id));

        final currentUserId = auth.user?.id;
        
        for (var alert in alerts) {
          // Hard-block alerts generated by THIS exact phone session
          if (NearbyAlertService.locallyGeneratedAlerts.contains(alert.alertId)) {
             print('[SOS Listener] Skipping alert ${alert.alertId}: This phone generated it.');
             continue;
          }
          
          // Check if I am the victim (Fallback logic)
          if (currentUserId != null && alert.userId == currentUserId) {
            print('[SOS Listener] Skipping alert ${alert.alertId}: I am the victim.');
            continue;
          }
          
          // Check if I am within 50,000 km (massively expanded for emulator testing)
          double distance = loc.distanceTo(alert.latitude, alert.longitude);
          print('==================================================');
          print('[SOS Listener] NEW ALERT DETECTED: ${alert.alertId}');
          print('[SOS Listener] Alert User: ${alert.userId} | My User: $currentUserId');
          print('[SOS Listener] Distance: ${distance.toInt()}m');
          
          if (distance <= 50000000) { // 50,000 KM threshold
            // ONLY trigger if we haven't popped it up for this alert yet
            if (!_activeAlertPopups.contains(alert.alertId)) {
              print('[SOS Listener] 🚨 SYSTEM CONDITIONS MET! TRIGGERING POPUP!');
              _activeAlertPopups.add(alert.alertId);

              // 1. Show Top-Bar Local Notification (Does NOT crash on fail)
              try {
                notify.showNotification(
                  title: '🚨 NEARBY EMERGENCY',
                  body: '${alert.userName} needs help nearby! Tap to respond.',
                  payload: {
                    'alert_id': alert.alertId,
                    'type': 'emergency_dispatch',
                  },
                );
              } catch (e) {
                print('[SOS Listener] Local notification warning: $e');
              }

              // 2. Auto-Popup Responder Screen Safely
              WidgetsBinding.instance.addPostFrameCallback((_) {
                if (mounted) {
                  try {
                    print('[SOS Listener] Pushing ResponderAlertScreen onto Navigator...');
                    Navigator.push(
                      context,
                      MaterialPageRoute(
                        builder: (_) => ResponderAlertScreen(
                          alertData: {
                            'alert_id': alert.alertId,
                            'victim_name': alert.userName,
                            'lat': alert.latitude.toString(),
                            'lng': alert.longitude.toString(),
                            'type': alert.tier == 'tier1' ? 'tier1_alert' : 'tier2_alert',
                          },
                        ),
                      ),
                    ).then((_) {
                      print('[SOS Listener] ResponderAlertScreen closed.');
                    });
                  } catch (e) {
                     print('[SOS Listener] FATAL ERROR PUSHING SCREEN: $e');
                  }
                } else {
                  print('[SOS Listener] Cannot push screen: HomeDashboard is not mounted.');
                }
              });
            } else {
              print('[SOS Listener] Alert ${alert.alertId} already in popup memory. Ignoring.');
            }
          } else {
            print('[SOS Listener] Alert ${alert.alertId} is too far away. Ignored.');
          }
        }

      });

      // ── Sync FCM Token ──
      FirebaseMessaging.instance.getToken().then((token) {
        if (token != null) {
          final auth = Provider.of<AuthProvider>(context, listen: false);
          if (auth.user != null) {
            auth.updateProfile({'fcm_token': token});
            
            // Sync user ID with BackgroundService so the victim doesn't get their own SOS push
            FlutterBackgroundService().invoke('setUserId', {'id': auth.user!.id});
          }
        }
      });
    });
  }
  @override
  void dispose() {
    _sosSubscription?.cancel();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppTheme.background,
      body: _screens[_currentIndex],
      bottomNavigationBar: Container(
        decoration: BoxDecoration(
          color: AppTheme.white,
          boxShadow: [
            BoxShadow(
              color: Colors.black.withAlpha(10),
              blurRadius: 20,
              offset: const Offset(0, -4),
            ),
          ],
        ),
        child: BottomNavigationBar(
          currentIndex: _currentIndex,
          onTap: (i) => setState(() => _currentIndex = i),
          items: const [
            BottomNavigationBarItem(icon: Icon(Icons.home_rounded), label: 'Home'),
            BottomNavigationBarItem(icon: Icon(Icons.map_rounded), label: 'Live Map'),
            BottomNavigationBarItem(icon: Icon(Icons.notifications_rounded), label: 'Alerts'),
            BottomNavigationBarItem(icon: Icon(Icons.person_rounded), label: 'Profile'),
          ],
        ),
      ),
    );
  }
}

