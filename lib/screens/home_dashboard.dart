  void _showSimulateDialog(BuildContext context, AgentProvider agent) {
    showDialog(
      context: context,
      builder: (_) => AlertDialog(
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
        title: Row(
          children: [
            const Icon(Icons.warning_amber_rounded, color: AppTheme.cautionYellow),
            const SizedBox(width: 10),
            const Text('Simulate Danger'),
          ],
        ),
        content: const Text(
          'This will simulate the AI agent pipeline:\n\n'
          '1. Detection Agent → Analyze sensors\n'
          '2. Context Agent → Check location risk\n'
          '3. Decision Agent → Calculate risk score\n'
          '4. Response Agent → Dispatch alerts\n\n'
          'No real emergency will be triggered.',
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context),
            child: const Text('Cancel'),
          ),
          ElevatedButton(
            onPressed: () {
              Navigator.pop(context);
              _runSimulation(context, agent);
            },
            style: ElevatedButton.styleFrom(backgroundColor: AppTheme.dangerRed),
            child: const Text('Simulate', style: TextStyle(color: Colors.white)),
          ),
        ],
      ),
    );
  }

  void _triggerSOS(BuildContext context, AgentProvider agent) {
    _runSimulation(context, agent);
  }

  void _runSimulation(BuildContext context, AgentProvider agent) {
    final auth = Provider.of<AuthProvider>(context, listen: false);
    final loc = Provider.of<LocationProvider>(context, listen: false);
    final user = auth.user ?? UserModel(id: 'demo', name: 'Demo User', phone: '', email: '');
    agent.runDangerSimulation(
      user: user,
      latitude: loc.latitude ?? AppConstants.defaultLat,
      longitude: loc.longitude ?? AppConstants.defaultLng,
    );
    _showAgentProgress(context, agent);
  }

  void _showAgentProgress(BuildContext context, AgentProvider agent) {
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(24)),
      ),
      builder: (_) => DraggableScrollableSheet(
        initialChildSize: 0.6,
        minChildSize: 0.3,
        maxChildSize: 0.9,
        expand: false,
        builder: (_, controller) => Consumer<AgentProvider>(
          builder: (_, ag, __) => Container(
            padding: const EdgeInsets.all(24),
            child: ListView(
              controller: controller,
              children: [
                Center(
                  child: Container(
                    width: 40,
                    height: 4,
                    decoration: BoxDecoration(
                      color: AppTheme.grey300,
                      borderRadius: BorderRadius.circular(2),
                    ),
                  ),
                ),
                const SizedBox(height: 20),
                Text('Agent Pipeline', style: AppTheme.headingMedium),
                const SizedBox(height: 4),
                Text('Multi-agent risk analysis', style: AppTheme.bodyMedium),
                const SizedBox(height: 20),
                ...ag.agentLog.map((log) => Padding(
                      padding: const EdgeInsets.only(bottom: 12),
                      child: Row(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Icon(
                            log.contains('✅')
                                ? Icons.check_circle
                                : log.contains('🔵')
                                    ? Icons.play_circle_fill
                                    : Icons.circle,
                            color: log.contains('✅')
                                ? AppTheme.safeGreen
                                : AppTheme.primaryBlue,
                            size: 20,
                          ),
                          const SizedBox(width: 12),
                          Expanded(
                            child: Text(log, style: AppTheme.bodyMedium),
                          ),
                        ],
                      ),
                    )),
                if (ag.isProcessing)
                  const Center(child: CircularProgressIndicator(color: AppTheme.primaryBlue)),
                if (!ag.isProcessing && ag.agentLog.isNotEmpty) ...[
                  const SizedBox(height: 16),
                  SizedBox(
                    width: double.infinity,
                    child: ElevatedButton(
                      onPressed: () => Navigator.pop(context),
                      style: ElevatedButton.styleFrom(
                        backgroundColor: AppTheme.safeGreen,
                        padding: const EdgeInsets.symmetric(vertical: 16),
                      ),
                      child: const Text('✅ Mark as Resolved', style: TextStyle(color: Colors.white)),
                    ),
                  ),
                ],
              ],
            ),
          ),
        ),
      ),
    );
  }
